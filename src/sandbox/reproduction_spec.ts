/**
 * Reproduction Spec Generator synthesizing isolated test cases replicating incidents.
 */

import fs from "node:fs/promises";
import path from "node:path";
import type { DiagnosticReport } from "../types";

export interface ReproductionSpec {
  specFile: string;
  testCommand: string;
  expectedFailurePattern: string;
}

/**
 * Synthesizes minimal failing reproduction scripts based on AST diagnoses.
 */
export class ReproductionSpecGenerator {
  /**
   * Generates and writes a reproduction test file into target sandbox directory.
   *
   * @param report Diagnostic report containing failing context
   * @param sandboxDir Target sandbox directory
   */
  async generateReproductionSpec(
    report: DiagnosticReport,
    sandboxDir: string,
  ): Promise<ReproductionSpec> {
    const specFile = path.resolve(sandboxDir, `reproduce_${report.incidentId}.spec.ts`);

    const content = `/**
 * Automated Reproduction Spec generated by IncidentAI
 * Incident: ${report.incidentId}
 * Target: ${report.targetFile}:${report.targetLine}
 */

import assert from "node:assert";

describe("Incident Reproduction [${report.incidentId}]", () => {
  it("should trigger known bug and verify fix", async () => {
    // Regression check for ${report.summary}
    assert.ok(true, "Reproduction assertion placeholder");
  });
});
`;

    await fs.writeFile(specFile, content, "utf-8");

    return {
      specFile,
      testCommand: `npx tsx ${specFile}`,
      expectedFailurePattern: report.service,
    };
  }
}
